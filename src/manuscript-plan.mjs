/**
 * Plan the projection of one manuscript (ordered Markdown parts, a metadata file, a CSL-YAML
 * bibliography and a CSL style) into publication formats as exact pandoc argument vectors.
 *
 * Everything here is pure: no filesystem, no clock, no process. Paths in a plan are relative
 * to the plan's `rootDir` and pandoc is run with that directory as its working directory, so
 * the argument vectors are identical on every machine that builds the same manuscript.
 */

export const PLAN_KIND = "manuscript-projection-plan";
export const FORMATS = Object.freeze(["pdf", "html", "docx", "epub", "jats"]);
export const PDF_ENGINES = Object.freeze(["xelatex", "lualatex", "pdflatex"]);
const JATS_FLAVORS = Object.freeze(["archiving", "publishing", "articleauthoring"]);

const OUTPUT = Object.freeze({
  pdf: { extension: "pdf", mediaType: "application/pdf" },
  html: { extension: "html", mediaType: "text/html" },
  docx: { extension: "docx", mediaType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document" },
  epub: { extension: "epub", mediaType: "application/epub+zip" },
  jats: { extension: "jats.xml", mediaType: "application/jats+xml" },
});

/**
 * What can honestly be promised about the bytes of each format when the same plan is run again
 * with the same pandoc, the same TeX Live and the same fonts. Measured, not assumed: see the
 * "Reproducibility" section of the README and test/reproducibility.integration.test.mjs.
 */
export const REPRODUCIBILITY = Object.freeze({
  html: Object.freeze({ level: "byte-identical", requires: ["same pandoc version"], caveats: [] }),
  jats: Object.freeze({ level: "byte-identical", requires: ["same pandoc version"], caveats: [] }),
  docx: Object.freeze({ level: "byte-identical", requires: ["same pandoc version", "SOURCE_DATE_EPOCH"], caveats: ["core.xml dates and zip entry times come from SOURCE_DATE_EPOCH"] }),
  epub: Object.freeze({ level: "byte-identical", requires: ["same pandoc version", "SOURCE_DATE_EPOCH", "a fixed identifier in the metadata file"], caveats: ["without an identifier in the metadata, pandoc mints a random UUID"] }),
  pdf: Object.freeze({
    level: "byte-identical-with-pinned-toolchain",
    requires: ["same pandoc version", "same TeX Live release and same installed fonts", "SOURCE_DATE_EPOCH with FORCE_SOURCE_DATE=1", "the generated reproducibility header"],
    caveats: ["the PDF names its producer and TeX Live release, so different toolchains differ by design", "system fonts (xelatex, lualatex fontspec) are embedded and must match byte for byte"],
  }),
});

const refuse = (reason, message) => Object.freeze({ ok: false, refusal: Object.freeze({ reason, message }) });

/** A path inside the root: relative, "/"-separated, no empty/"."/".." segments, not an option. */
export function isRootRelativePath(path) {
  return typeof path === "string" && path !== "" && !path.startsWith("/") && !path.startsWith("-") && !path.includes("\\")
    && !/[\u0000-\u001f]/u.test(path) && path.split("/").every((segment) => segment !== "" && segment !== "..")
    && !/^[A-Za-z]:/u.test(path);
}

const clean = (path) => path.split("/").filter((segment) => segment !== ".").join("/") || ".";

/** The LaTeX header that removes the timestamps and ids a PDF engine would otherwise write. */
export function reproducibilityHeader(engine) {
  const lines = ["% generated by project-document-through-pandoc: removes build-time values from the PDF"];
  if (engine === "pdflatex") lines.push("\\pdfinfoomitdate=1", "\\pdftrailerid{}", "\\pdfsuppressptexinfo=-1");
  else if (engine === "lualatex") lines.push("\\pdfvariable omitcidset=1", "\\pdfvariable suppressoptionalinfo=\\numexpr 1+2+4+8+16+32+64+128+256+512\\relax");
  else lines.push("\\AtBeginDocument{\\special{pdf:trailerid [<00000000000000000000000000000000> <00000000000000000000000000000000>]}}");
  return `${lines.join("\n")}\n`;
}

function epochDate(epoch) {
  return new Date(epoch * 1000).toISOString().slice(0, 10);
}

function listOf(value, name, { required = false } = {}) {
  if (value === undefined) return required ? refuse("InvalidRequest", `${name} is required`) : [];
  if (!Array.isArray(value) || value.some((item) => typeof item !== "string")) return refuse("InvalidRequest", `${name} must be an array of strings`);
  return value;
}

const stringMap = (value, name) => {
  if (value === undefined) return {};
  if (value === null || typeof value !== "object" || Array.isArray(value) || Object.values(value).some((item) => typeof item !== "string")) return refuse("InvalidRequest", `${name} must be an object of strings`);
  for (const key of Object.keys(value)) if (!/^[A-Za-z][A-Za-z0-9_-]*$/u.test(key)) return refuse("InvalidRequest", `${name} key ${JSON.stringify(key)} is not a plain name`);
  return value;
};

/**
 * Plan the projection of a manuscript into one or more output formats.
 * @param {object} request `{parts, metadataFile?, bibliography?, cslStyle?, formats, sourceDateEpoch, rootDir?,
 *   outputDir?, basename?, pdfEngine?, resourcePaths?, citeproc?, numberSections?, toc?, tocDepth?, from?, date?,
 *   referenceDoc?, css?, embedResources?, jatsFlavor?, variables?, metadata?, requirePandocVersion?}`.
 * @param {{exists?: (path: string) => boolean}} [ports] When `exists` is supplied, every input file is checked for presence.
 * @returns {{ok: true, plan: object}|{ok: false, refusal: {reason: string, message: string}}}
 */
export function planManuscriptProjection(request, ports = {}) {
  if (request === null || typeof request !== "object" || Array.isArray(request)) return refuse("InvalidRequest", "request must be an object");
  const {
    rootDir = ".", outputDir = "build", basename = "manuscript", pdfEngine = "xelatex", citeproc = true, numberSections = false,
    toc = false, tocDepth, from = "markdown", embedResources = false, jatsFlavor = "archiving", sourceDateEpoch,
  } = request;

  if (typeof rootDir !== "string" || rootDir === "") return refuse("InvalidRequest", "rootDir must be a non-empty string");
  const parts = listOf(request.parts, "parts", { required: true });
  if (!Array.isArray(parts)) return parts;
  if (parts.length === 0) return refuse("NoManuscriptParts", "a manuscript needs at least one part");
  const formats = listOf(request.formats, "formats", { required: true });
  if (!Array.isArray(formats)) return formats;
  if (formats.length === 0) return refuse("NoOutputFormats", "at least one output format is required");
  for (const format of formats) if (!FORMATS.includes(format)) return refuse("UnsupportedFormat", `format ${JSON.stringify(format)} is not one of ${FORMATS.join(", ")}`);
  if (new Set(formats).size !== formats.length) return refuse("InvalidRequest", "formats must not repeat");
  if (!Number.isSafeInteger(sourceDateEpoch) || sourceDateEpoch < 0) return refuse("InvalidSourceDateEpoch", "sourceDateEpoch must be a non-negative integer number of seconds; derive it from the manuscript's commit time");
  if (!PDF_ENGINES.includes(pdfEngine)) return refuse("UnsupportedPdfEngine", `pdfEngine must be one of ${PDF_ENGINES.join(", ")}`);
  if (!JATS_FLAVORS.includes(jatsFlavor)) return refuse("InvalidRequest", `jatsFlavor must be one of ${JATS_FLAVORS.join(", ")}`);
  if (typeof basename !== "string" || !/^[A-Za-z0-9][A-Za-z0-9._-]*$/u.test(basename)) return refuse("InvalidRequest", "basename must be a plain file name stem");
  if (tocDepth !== undefined && (!Number.isInteger(tocDepth) || tocDepth < 1 || tocDepth > 6)) return refuse("InvalidRequest", "tocDepth must be an integer from 1 to 6");
  if (typeof from !== "string" || !/^[a-z_]+([+-][a-z_]+)*$/u.test(from)) return refuse("InvalidRequest", "from must be a pandoc input format such as markdown or markdown+smart");
  if (request.date !== undefined && typeof request.date !== "string") return refuse("InvalidRequest", "date must be a string or \"source-date-epoch\"");
  for (const [name, value] of [["citeproc", citeproc], ["numberSections", numberSections], ["toc", toc], ["embedResources", embedResources]]) {
    if (typeof value !== "boolean") return refuse("InvalidRequest", `${name} must be a boolean`);
  }
  const resourcePaths = request.resourcePaths === undefined ? ["."] : listOf(request.resourcePaths, "resourcePaths");
  if (!Array.isArray(resourcePaths)) return resourcePaths;
  const variables = stringMap(request.variables, "variables");
  if (variables.ok === false) return variables;
  const metadata = stringMap(request.metadata, "metadata");
  if (metadata.ok === false) return metadata;
  if (request.requirePandocVersion !== undefined && !/^[0-9]+(\.[0-9]+)*$/u.test(request.requirePandocVersion)) return refuse("InvalidRequest", "requirePandocVersion must be a dotted version such as 3.1.3");

  const paths = { metadataFile: request.metadataFile, bibliography: request.bibliography, cslStyle: request.cslStyle, referenceDoc: request.referenceDoc, css: request.css };
  for (const [name, value] of Object.entries(paths)) if (value !== undefined && !isRootRelativePath(value)) return refuse("PathEscapesRoot", `${name} ${JSON.stringify(value)} must be a relative path inside the root`);
  for (const path of [...parts, ...resourcePaths, outputDir]) if (!isRootRelativePath(path)) return refuse("PathEscapesRoot", `path ${JSON.stringify(path)} must be a relative path inside the root`);
  if (citeproc && paths.bibliography === undefined) return refuse("MissingBibliography", "citeproc is on but no bibliography (CSL-YAML) was named");
  if (citeproc && paths.cslStyle === undefined) return refuse("MissingStyle", "citeproc is on but no CSL style was named");
  if (paths.referenceDoc !== undefined && !formats.includes("docx")) return refuse("InvalidRequest", "referenceDoc applies to docx output only");
  if (paths.css !== undefined && !formats.includes("html")) return refuse("InvalidRequest", "css applies to html output only");

  const cleanParts = parts.map(clean), cleanOutputDir = clean(outputDir);
  const inputs = {
    parts: cleanParts,
    ...(paths.metadataFile === undefined ? {} : { metadataFile: clean(paths.metadataFile) }),
    ...(paths.bibliography === undefined ? {} : { bibliography: clean(paths.bibliography) }),
    ...(paths.cslStyle === undefined ? {} : { cslStyle: clean(paths.cslStyle) }),
    ...(paths.referenceDoc === undefined ? {} : { referenceDoc: clean(paths.referenceDoc) }),
    ...(paths.css === undefined ? {} : { css: clean(paths.css) }),
    resourcePaths: resourcePaths.map(clean),
  };

  if (typeof ports.exists === "function") {
    const named = [
      ...inputs.parts.map((path) => ["MissingPart", "manuscript part", path]),
      ...[["MissingMetadata", "metadata file", inputs.metadataFile], ["MissingBibliography", "bibliography", inputs.bibliography], ["MissingStyle", "CSL style", inputs.cslStyle], ["MissingReferenceDoc", "reference document", inputs.referenceDoc], ["MissingStylesheet", "stylesheet", inputs.css]].filter((entry) => entry[2] !== undefined),
    ];
    for (const [reason, label, path] of named) if (!ports.exists(path)) return refuse(reason, `${label} ${path} does not exist under ${rootDir}`);
  }

  const date = request.date === "source-date-epoch" ? epochDate(sourceDateEpoch) : request.date;
  const common = [
    `--from=${from}`,
    "--standalone",
    ...(inputs.metadataFile === undefined ? [] : [`--metadata-file=${inputs.metadataFile}`]),
    ...Object.entries(metadata).sort(([a], [b]) => (a < b ? -1 : 1)).map(([key, value]) => `--metadata=${key}:${value}`),
    ...(date === undefined ? [] : [`--metadata=date:${date}`]),
    ...Object.entries(variables).sort(([a], [b]) => (a < b ? -1 : 1)).map(([key, value]) => `--variable=${key}:${value}`),
  ];
  const tail = [
    ...(numberSections ? ["--number-sections"] : []),
    ...(toc ? ["--toc", ...(tocDepth === undefined ? [] : [`--toc-depth=${tocDepth}`])] : []),
    `--resource-path=${inputs.resourcePaths.join(":")}`,
    ...(inputs.bibliography === undefined ? [] : [`--bibliography=${inputs.bibliography}`]),
    ...(inputs.cslStyle === undefined ? [] : [`--csl=${inputs.cslStyle}`]),
    ...(citeproc ? ["--citeproc"] : []),
  ];

  const supportFiles = [], outputs = [];
  for (const format of formats) {
    const output = `${cleanOutputDir === "." ? "" : `${cleanOutputDir}/`}${basename}.${OUTPUT[format].extension}`;
    const specific = [];
    if (format === "pdf") {
      const header = `${cleanOutputDir === "." ? "" : `${cleanOutputDir}/`}.reproducibility-${pdfEngine}.tex`;
      supportFiles.push({ path: header, role: "support", mediaType: "application/x-tex", content: reproducibilityHeader(pdfEngine) });
      specific.push("--to=pdf", `--pdf-engine=${pdfEngine}`, `--include-in-header=${header}`);
    } else if (format === "html") {
      specific.push("--to=html5", ...(inputs.css === undefined ? [] : [`--css=${inputs.css}`]), ...(embedResources ? ["--embed-resources"] : []));
    } else if (format === "docx") {
      specific.push("--to=docx", ...(inputs.referenceDoc === undefined ? [] : [`--reference-doc=${inputs.referenceDoc}`]));
    } else if (format === "epub") {
      specific.push("--to=epub3");
    } else {
      specific.push(`--to=jats_${jatsFlavor}`);
    }
    outputs.push({
      format,
      path: output,
      mediaType: OUTPUT[format].mediaType,
      reproducibility: REPRODUCIBILITY[format],
      argv: [...common, ...specific, ...tail, `--output=${output}`, ...inputs.parts],
    });
  }

  const dedupe = new Map(supportFiles.map((file) => [file.path, file]));
  return Object.freeze({
    ok: true,
    plan: {
      kind: PLAN_KIND,
      version: 1,
      rootDir,
      command: "pandoc",
      env: { FORCE_SOURCE_DATE: "1", SOURCE_DATE_EPOCH: String(sourceDateEpoch), TZ: "UTC" },
      sourceDateEpoch,
      outputDir: cleanOutputDir,
      ...(formats.includes("pdf") ? { pdfEngine } : {}),
      ...(request.requirePandocVersion === undefined ? {} : { requirePandocVersion: request.requirePandocVersion }),
      inputs,
      supportFiles: [...dedupe.values()],
      outputs,
    },
  });
}
